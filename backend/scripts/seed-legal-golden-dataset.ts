async function main() {
  console.log('=== Seeding Golden Legal Dataset V1 ===')
  let rCount = 0
  for (const r of regulations) {
    const existing = await prisma.legalRegulation.findFirst({ where: { title: r.title } })
    if (!existing) {
      await prisma.legalRegulation.create({ data: r })
      rCount++
      console.log(`  + ${r.title}`)
    } else {
      console.log(`  ✓ ${r.title} (已存在)`)
    }
  }
  console.log(`\n新增: ${rCount} 条 | 总数: ${await prisma.legalRegulation.count()}`)
  await prisma.$disconnect()
}

main().catch((err) => { console.error(err); process.exit(1) })
