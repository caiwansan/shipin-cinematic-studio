【核心规则】
1. 角色提取规则：逐一读取剧本中出现的每个角色（包括主角、配角、反派、路人），只要该角色有台词或有明确描述，就必须加入 characters 数组。**不得遗漏任何角色**。每个角色必须有完整的 character spec（name, description, gender, age, role, personality, voiceType）。
2. 场景提取规则：逐一识别剧本中出现的每个地点/场景。如果有多个场景切换，每个场景都必须加入 scenes 数组。**不得遗漏**。
3. 道具提取规则：识别剧本中所有有明确视觉特征的道具（武器、法宝、饰品、工具等）。
4. 台词提取规则：逐行提取每个角色的对白，标注说话角色和语气。
5. 情绪提取规则：根据剧情发展，标注每段关键节点的情绪状态。
6. 视频段落拆分规则：按剧情发展拆分成连贯的段落，**每段时长10秒**（duration: 10）。段落之间要有逻辑连贯性，段落内部按镜头切分成 beats（每1-3秒一个 beat）。

